export const tables: Record<string, Record<Key, string>> = { en, fr, de, it, ja, ko, pt, es };

/** Language from the phone (e.g. "pt-BR" → "pt"); `?lang=xx` overrides it for testing. Anything else gets English. */
function pickLang(): string {
  const forced = new URLSearchParams(location.search).get("lang");
  const code = (forced || navigator.language || "en").slice(0, 2).toLowerCase();
  return code in tables ? code : "en";
}
export const lang = pickLang();
document.documentElement.lang = lang;

/** The voice to ask Android's text-to-speech for: the regional variant the store listing targets. */
export const speechLang = ({ pt: "pt-BR", es: "es-US", en: "en-US", fr: "fr-FR", de: "de-DE", it: "it-IT", ja: "ja-JP", ko: "ko-KR" } as Record<string, string>)[lang] ?? "en-US";

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return (tables[lang][key] ?? en[key]).replace(/\{(\w+)\}/g, (_, v) => String(vars[v] ?? ""));
}
